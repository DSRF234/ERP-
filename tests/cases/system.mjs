/* 顶栏修改密码 */
const changePwd = async (api, oldP, newP) => {
  await api.c.eval(`document.querySelector('.user').click(); true`)
  await api.c.sleep(400)
  await api.c.eval(`(() => {
    const it = [...document.querySelectorAll('.el-dropdown-menu__item')].find(x => (x.innerText||'').includes('修改密码'))
    if (!it) return 'no-item'; it.click(); return 'ok'
  })()`)
  await api.c.sleep(500)
  const filled = await api.c.eval(`(() => {
    const dlg = ${VIS}
    if (!dlg) return 'no-dialog'
    const ins = [...dlg.querySelectorAll('input')]
    const s = Object.getOwnPropertyDescriptor(window.HTMLInputElement.prototype, 'value').set
    ;[${JSON.stringify(oldP)}, ${JSON.stringify(newP)}, ${JSON.stringify(newP)}].forEach((v, i) => {
      if (!ins[i]) return
      s.call(ins[i], v); ins[i].dispatchEvent(new Event('input', { bubbles: true }))
    })
    return 'ok'
  })()`)
  if (filled !== 'ok') return filled
  await api.c.sleep(200)
  await api.c.eval(`(() => {
    const dlg = ${VIS}
    const b = [...dlg.querySelectorAll('.el-dialog__footer button')].find(x => (x.innerText||'').trim() === '确认修改')
    if (!b) return 'no-btn'; b.click(); return 'ok'
  })()`)
  await api.c.sleep(700)
  return 'ok'
}

