    await api.go('/aftersale/doing')
    const r = await api.rowBy(orderNo.replace(/^.*$/, m => m)) // placeholder
    const row = await api.rowBy(D[Object.keys(D).find(x => D[x] === orderNo)] || orderNo)
    k.is(!!row, '处理中存在该单')
    k.is(row && row.includes(expectQueue), `当前状态「${expectQueue}」（${row?.slice(0, 50)}）`)
